#6.f-string，核心结构：f"文字{变量}文字"，f不能忘
name="wzr"
age=23
print(f"我的名字是{name},今年{age}岁")

#f-string中也可以直接计算
a = 10
b = 20

print(f"a + b = {a + b}")

#7.f-string控制小数位数
piece=3.1415926
print(f"piece = {piece:.2f}")#输出3.14， .2f的含义是保留两位小数

