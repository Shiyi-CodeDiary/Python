#1.input():接收用户输入，input得到的数据永远是字符串
name=input("请输入名字：")
print("名字是："+name)

#所以做数学运算前通常要转换类型
a = int(input("请输入第一个数字：")) #10
b = int(input("请输入第二个数字：")) #20

print(a + b) #30

#如果不做类型转换
a = input("a：")#10
b = input("b：")#20

print(a + b) #输出1020，字符串的+是拼接

